/**
 * The roster's face boxes, stored.
 *
 * Fitting a face box is a grid search over the body (`fitFace`), and it is
 * most of the cost of deriving a shape. The roster's bodies are fixed, so
 * their boxes are worked out ahead of time into `face-boxes.generated.ts`
 * and read on first use. Each is stored with a digest of exactly what it
 * was worked out from — the body's outline, the left-eye nudge, the face
 * hint and the outlines it avoids — so a body redrawn, or replaced through
 * `defineShape`, is fitted afresh rather than given a stale box. A test works
 * every box out again and fails, naming the command to run, if one no longer
 * matches.
 */
import { GENERATE_COMMAND } from '../core/generated.js';
import type { FaceBox, Point } from '../core/types.js';

/** What a face box is worked out from: the arguments of `fitFace`. */
export interface FaceInputs {
  points: readonly Point[];
  leftDX: number;
  hint: Point | undefined;
  avoid: readonly (readonly Point[])[];
}

/** A stored face box and the digest of the inputs it was worked out from. */
export interface StoredFaceBox {
  digest: string;
  box: FaceBox;
}

/**
 * A digest of a face box's inputs, over the exact bits of every number, so
 * any change to them, however small, is a different digest.
 */
export function faceInputsDigest({ points, leftDX, hint, avoid }: FaceInputs): string {
  const bits = new Float64Array(1);
  const words = new Uint32Array(bits.buffer);
  let h = 0x811c9dc5;
  const mix = (v: number): void => {
    bits[0] = v;
    h = Math.imul(h ^ words[0]!, 0x01000193) >>> 0;
    h = Math.imul(h ^ words[1]!, 0x01000193) >>> 0;
  };
  const ring = (outline: readonly Point[]): void => {
    mix(outline.length);
    for (const [x, y] of outline) {
      mix(x);
      mix(y);
    }
  };
  ring(points);
  mix(leftDX);
  mix(hint ? 1 : 0);
  if (hint) ring([hint]);
  mix(avoid.length);
  for (const outline of avoid) ring(outline);
  return h.toString(36);
}

/** The source of `face-boxes.generated.ts` for these boxes. Numbers are written in full, so a stored box is the computed one exactly. */
export function faceBoxesModule(rows: Record<string, StoredFaceBox>): string {
  const entries = Object.entries(rows).map(([id, { digest, box }]) => {
    const fields = (['x', 'y', 'sx', 'sy', 'eye', 'leftDX'] as const).map((key) => `${key}: ${box[key]}`);
    return `  ${id}: { digest: '${digest}', box: { ${fields.join(', ')} } },`;
  });
  return [
    '/*',
    " * The roster's face boxes, worked out by `fitFace` (`shapes/fit-face.ts`). A body whose",
    ' * digest no longer matches is fitted afresh on first use.',
    ` * Generated by \`${GENERATE_COMMAND}\`; do not edit by hand.`,
    ' */',
    "import type { StoredFaceBox } from './face-boxes.js';",
    '',
    'export const FACE_BOXES: Partial<Record<string, StoredFaceBox>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}
